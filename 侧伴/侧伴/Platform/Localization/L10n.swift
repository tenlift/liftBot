import Foundation

/// UI language is independent of speech recognition and never rewrites saved user content.
nonisolated enum AppLanguage: String, CaseIterable {
    case system, chinese = "zh-Hans", english = "en"

    static let preferenceKey = "interfaceLanguage"
    static func current(defaults: UserDefaults = .standard) -> AppLanguage {
        AppLanguage(rawValue: defaults.string(forKey: preferenceKey) ?? "system") ?? .system
    }
    func resolved(preferredLanguages: [String] = Locale.preferredLanguages) -> AppLanguage {
        guard self == .system else { return self }
        return preferredLanguages.first?.hasPrefix("zh") == true ? .chinese : .english
    }
    var locale: Locale { Locale(identifier: resolved() == .chinese ? "zh-Hans" : "en") }
}

nonisolated enum L10n {
    static func text(_ key: String, _ arguments: String...) -> String {
        render(key, arguments: arguments, language: AppLanguage.current())
    }

    static func render(_ key: String, arguments: [String] = [], language: AppLanguage) -> String {
        let template = language.resolved() == .english ? english[key] ?? key : key
        // Replace only tokens in the template, never tokens inside user-supplied arguments.
        let regex = try! NSRegularExpression(pattern: #"\{([0-9]+)\}"#)
        let source = template as NSString
        var result = template
        for match in regex.matches(in: template, range: NSRange(location: 0, length: source.length)).reversed() {
            guard let index = Int(source.substring(with: match.range(at: 1))), arguments.indices.contains(index),
                  let range = Range(match.range, in: result) else { continue }
            result.replaceSubrange(range, with: arguments[index])
        }
        return result
    }

